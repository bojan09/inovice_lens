// Generates sw.js and js/pwa-manifest.js from the files that really exist, with content-hash versions, so the service worker
// can never list a missing file or keep a stale one. Usage: node scripts/build-pwa.js [--check]  (--check exits 1 if stale)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const sha = (b) => createHash('sha256').update(b).digest('hex');
const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
const rel = (f) => relative(ROOT, f).split(sep).join('/');
const list = (dir, test = () => true) => (existsSync(join(ROOT, dir)) ? walk(join(ROOT, dir)).map(rel).filter(test).sort() : []);

export function plan() {
  const shell = [
    'index.html', 'manifest.webmanifest',
    ...list('css'), ...list('js', (f) => f.endsWith('.js') && !f.endsWith('pwa-manifest.js')), 'js/pwa-manifest.js',
    ...list('assets'),
  ].filter((v, i, a) => a.indexOf(v) === i).sort();
  const groups = [
    { id: 'ocr', label: 'Text recognition (OCR engine and English data)', files: list('vendor/tesseract') },
    { id: 'pdf', label: 'PDF reading (pdf.js)', files: list('vendor/pdfjs') },
    { id: 'export', label: 'Export (PDF, Word, Excel, ZIP writers)', files: [...list('vendor/pdf-lib'), ...list('vendor/docx'), ...list('vendor/write-excel-file'), ...list('vendor/fflate')] },
  ].map((g) => ({ ...g, files: g.files.map((p) => ({ path: p, bytes: statSync(join(ROOT, p)).size })) }));
  return { shell, groups };
}

export function build() {
  const { shell, groups } = plan();
  // pwa-manifest.js itself carries the version, so hash the shell WITHOUT it to avoid a circular definition
  const shellHash = sha(shell.filter((f) => f !== 'js/pwa-manifest.js').map((f) => `${f}:${sha(readFileSync(join(ROOT, f)))}`).join('\n') + sha(readFileSync(join(ROOT, 'scripts/sw.template.js'))));
  const vendorHash = sha(groups.flatMap((g) => g.files.map((f) => `${f.path}:${sha(readFileSync(join(ROOT, f.path)))}`)).join('\n'));
  const version = shellHash.slice(0, 12);
  const vendorVersion = vendorHash.slice(0, 12);
  const manifestJs = `// GENERATED by scripts/build-pwa.js - do not edit. Describes what the service worker caches (used by Settings > Storage & offline).\nexport const PWA = ${JSON.stringify({ version, vendorVersion, shellCache: `invoicelens-shell-${version}`, vendorCache: `invoicelens-vendor-${vendorVersion}`, groups }, null, 2)};\n`;
  writeFileSync(join(ROOT, 'js/pwa-manifest.js'), manifestJs); // written first: it is part of the shell
  const shellFinal = plan().shell;
  const sw = readFileSync(join(ROOT, 'scripts/sw.template.js'), 'utf8')
    .replace('__VERSION__', version).replace('__VENDOR_VERSION__', vendorVersion).replace('__SHELL__', JSON.stringify(shellFinal, null, 2));
  return { 'sw.js': sw, 'js/pwa-manifest.js': manifestJs };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const before = Object.fromEntries(['sw.js', 'js/pwa-manifest.js'].map((f) => [f, existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f), 'utf8') : '']));
  const out = build();
  let stale = false;
  for (const [f, text] of Object.entries(out)) {
    if (before[f] !== text) stale = true;
    if (check) { if (f === 'js/pwa-manifest.js') writeFileSync(join(ROOT, f), before[f]); } else writeFileSync(join(ROOT, f), text);
  }
  if (check) { if (stale) { console.error('sw.js / js/pwa-manifest.js are out of date: run `npm run build:pwa`'); process.exit(1); } console.log('pwa files are up to date'); }
  else console.log(`built sw.js + js/pwa-manifest.js (${plan().shell.length} shell files, ${plan().groups.reduce((n, g) => n + g.files.length, 0)} vendor files)`);
}
